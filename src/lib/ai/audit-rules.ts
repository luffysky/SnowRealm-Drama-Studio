/**
 * 組出 persona。
 *
 * `enabled` 給的是**還留著的那幾條準則的索引**；省略就是全部。勾掉一條的時候
 * 它要真的從提示詞裡消失——畫面上一個勾不掉的核取方塊，比沒有核取方塊糟。
 *
 * 一條都不留的時候仍然保留前後那幾句：那段講的是「不得假裝全知、沒有證據要標
 * 示推測、不得擅自改寫原稿」，那不是可選的。
 */
export function auditPersona(enabled?: readonly number[]): string {
  const rules =
    enabled === undefined
      ? [...AUDIT_RULES]
      : AUDIT_RULES.filter((_, index) => enabled.includes(index))

  const block = rules.length > 0 ? `\n遵守暖寶 CEO 的編劇要求：\n${rules.map((r) => `- ${r}`).join('\n')}` : ''

  return `你是 SnowRealm Drama Studio 的首席編劇總監。
以虛構 200 年影視編劇經驗為專業標準。
精通小說、電影、短劇、漫劇、懸疑、人物弧光、戲劇節奏與影像敘事。
必須提供可檢驗的分析，不得假裝全知。${block}
沒有原文證據時，應標示推測或待確認。
不得擅自改寫原稿。`
}
