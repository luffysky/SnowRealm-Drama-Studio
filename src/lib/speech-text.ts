/**
 * 唸出來之前，把不該唸的東西拿掉 (Z140).
 *
 * 使用者聽到有聲書在唸「星號星號星號」。那不是正文裡的字——是**我們自己放
 * 進去的**：`htmlToText` 把 `<hr>` 這個場景分隔線轉成 `* * *`，當作純文字
 * 匯出時的視覺分隔。給眼睛看是對的，給 TTS 唸就變成三個「星號」。
 *
 * 這一類錯誤有個共同點：**排版符號在螢幕上是留白，在耳朵裡是字。** 所以
 * 轉語音這條路上必須有一道把它們拿掉的手續，而且要**兩邊共用**——閱讀器
 * 朗讀跟匯出音檔走同一份切段（`speech-split.ts`），這裡就掛在那上面。
 *
 * 分隔線不是刪掉就好，它**換成一段靜音**。場景換了而聲音一路接下去，聽起來
 * 就是前一場的話還沒說完；一段明顯的停頓才是那條線在書上做的事。
 *
 * 純函式，沒有瀏覽器也沒有資料庫。
 */

/**
 * 只會被當成排版、永遠不該唸出來的符號。
 *
 * 刻意不收中文破折號 `——`：它在正文裡是標點，單獨成段也可能是作者的安排，
 * 而把作者寫的東西當成雜訊刪掉，比多唸一個符號糟糕得多。
 */
/**
 * 整段只有分隔符號——`* * *`、`***`、`---`、`※※※`。
 *
 * 寫成**字面的** regex，不是用字串拼出來的。拼出來的那一版有兩個不會報錯
 * 的坑：`-` 夾在 `*` 跟 `_` 中間會被當成**字元範圍**（於是 `123` 也算分隔
 * 線），而 `\s` 寫在範本字串裡會被吃成 `s`（於是 `* * *` 反而不算）。
 * 兩個都編得過，兩個都安靜地錯。
 *
 * 連字號放在最後一個位置，那裡它只能是它自己。
 */
const DIVIDER = /^[*_=~#＊※·•◇◆☆★○●-]+$/

/**
 * 這一段是場景分隔線嗎。
 *
 * 空白先拿掉再比對，所以 `* * *` 跟 `***` 走同一條路。要求至少兩個符號：
 * 單獨一個 `-` 或 `*` 成段，更可能是正文的一部分被切壞，而不是作者畫的線。
 * 寧可多唸一個字，也不要吃掉一段話。
 */
export function isSceneBreak(text: string): boolean {
  const bare = text.replace(/\s/g, '')
  if (bare.length < 2) return false
  return DIVIDER.test(bare)
}

/**
 * 去掉行內的 Markdown 標記，留下字。
 *
 * 分兩段做，因為順序有差：
 *
 *  1. **成對的**先脫殼 —— `**重要**` 要變成「重要」，不是「重要」加兩個星號。
 *  2. **落單的**再掃掉 —— 星號跟反引號在中文小說裡沒有任何讀音，留著只會
 *     被唸出來。底線與波浪號只在成對時處理，單獨出現可能是作者真的寫了。
 *
 * 行首的 `#`、`>`、`1.` 也一起拿掉：那是標題與引言的記號，不是內容。
 */
export function stripInlineMarkup(text: string): string {
  return (
    text
      // 行首的區塊記號。
      .replace(/^[ \t]*#{1,6}[ \t]+/gm, '')
      .replace(/^[ \t]*>[ \t]*/gm, '')
      .replace(/^[ \t]*\d+[.)][ \t]+/gm, '')
      // 成對的強調。
      .replace(/\*\*\*(.+?)\*\*\*/g, '$1')
      .replace(/\*\*(.+?)\*\*/g, '$1')
      .replace(/~~(.+?)~~/g, '$1')
      .replace(/__(.+?)__/g, '$1')
      .replace(/`([^`]+)`/g, '$1')
      // 落單的。星號與反引號一律掃掉——它們不是中文標點。
      .replace(/[*`]/g, '')
      .replace(/[ \t]{2,}/g, ' ')
      .trim()
  )
}

/**
 * 一段正文，變成唸得出來的樣子。
 *
 * 回 `null` 表示這一段沒有任何要唸的東西（例如整段就是分隔線）。呼叫的人
 * 自己決定那要變成靜音還是直接跳過。
 */
export function speakableText(paragraph: string): string | null {
  if (isSceneBreak(paragraph)) return null
  const clean = stripInlineMarkup(paragraph)
  return clean.length > 0 ? clean : null
}

/** 場景分隔線換成多長的靜音。 */
export const SCENE_BREAK_MS = 1200
